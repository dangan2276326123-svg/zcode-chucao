# -*- coding: utf-8 -*-
"""PC 侧发送工具共用的**台架安全限值**（单一事实源，AGENTS 审查清单第 6 条）。

为什么要有这个文件：现在能往大板发帧的 PC 侧入口有两个——`tools/link_probe.py`
（命令行探针）与 `tools/bench_status.py --to`（记录器的 opt-in 发送面）。两者走的是
同一个 `bridge:9000`，同一块板子，所以限速这条安全不变量只能有一份：各写一个字面量，
下一次就是改了一份没改另一份，而"哪个闸生效"这种事没人会在台架上重新验一遍。

限速的理由（这些是**代码事实**，不是推测，出处都标着）：
  · 现在烧在板上的固件里，一条 NAV 就是进 AUTO 的钥匙：
    `firmware/retrofit.c:93` `if (len < 9 || estop_latched) return;` → `:98-101` 把
    `cmd_vl`/`cmd_vr` 钳到 **±1.0 m/s** → `:102` `mode = MODE_AUTO;`
    （批 1a 的 F1 修法正是把这一支拆掉，但**尚未实施、尚未烧**）；
  · 行走侧有斜率限制 `SLEW_ACC = 0.2 m/s²`（`firmware/retrofit.c:140`），所以
    "钳到 ±1.0"不等于安全——一条 0.9 的命令约 4.5 秒后**真的**把车推到 0.9 m/s。
    一台 2.15 m 宽、带着刀和滑台的机器在台架上跑 0.9 m/s，不需要更多形容词。

结论：PC 侧两个发送器都把 NAV 硬拦在 0.20 m/s，超限**拒发**（不是"发个 0 试试"），
并且当场把拒了这件事打在屏幕上。这个工具不是行车工具——要跑闭环请用 `pc/main.py`。
"""

# 台架 NAV 限速（m/s）：两个发送器共读这一个数。
NAV_BENCH_LIMIT_MPS = 0.20


def nav_exceeds_bench_limit(vl, vr):
    """True = 这条 NAV 超出台架限速，必须拒发。

    按 f32 的**线上值**比时要留一点余量：0.2 存成 f32 是 0.20000000298…，不留余量就会
    把"正好等于限值"这条边界拒掉；而 `link_probe` 是按命令行字面量判 `> 0.20`、放行它。
    同一个闸在两个发送器上必须给同一个答案，所以判定逻辑也放进这个文件里，而不只是数字。
    """
    return max(abs(float(vl)), abs(float(vr))) > NAV_BENCH_LIMIT_MPS + 1e-6
